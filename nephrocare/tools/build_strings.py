#!/usr/bin/env python3
"""Generates app/src/main/res/values*/strings.xml from tools/strings_src.py and checks
that every R.string / R.array used in the Kotlin sources exists."""
import os, re, sys
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from strings_src import S, ARRAYS  # noqa: E402

LANGS = [("values", 1), ("values-ar", 2), ("values-fr", 3), ("values-es", 4)]

def android_escape(text):
    t = escape(text)
    t = t.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if t.startswith("@") or t.startswith("?"):
        t = "\\" + t
    return t

def main():
    keys = [row[0] for row in S]
    dupes = {k for k in keys if keys.count(k) > 1}
    if dupes:
        sys.exit(f"duplicate keys: {sorted(dupes)}")
    for row in S:
        if len(row) != 5:
            sys.exit(f"row {row[0]} has {len(row)} columns")
        args = [sorted(set(re.findall(r"%\d\$[sd]", col))) for col in row[1:]]
        if any(a != args[0] for a in args):
            sys.exit(f"format arguments differ in {row[0]}: {args}")
    for name, (en, ar, fr, es) in ARRAYS.items():
        if not (len(en) == len(ar) == len(fr) == len(es)):
            sys.exit(f"array {name} lengths differ")

    for folder, col in LANGS:
        out = ['<?xml version="1.0" encoding="utf-8"?>',
               "<!-- Generated by tools/build_strings.py from tools/strings_src.py. Do not edit. -->",
               "<resources>"]
        for row in S:
            formatted = ' formatted="false"' if ("%" in row[col] and not re.search(r"%\d\$", row[col])) else ""
            out.append(f'    <string name="{row[0]}"{formatted}>{android_escape(row[col])}</string>')
        for name, langs in ARRAYS.items():
            out.append(f'    <string-array name="{name}">')
            for item in langs[col - 1]:
                out.append(f"        <item>{android_escape(item)}</item>")
            out.append("    </string-array>")
        out.append("</resources>")
        path = os.path.join(ROOT, "app/src/main/res", folder)
        os.makedirs(path, exist_ok=True)
        with open(os.path.join(path, "strings.xml"), "w", encoding="utf-8") as f:
            f.write("\n".join(out) + "\n")

    used = set()
    for dirpath, _, files in os.walk(os.path.join(ROOT, "app/src")):
        for fn in files:
            if fn.endswith(".kt"):
                with open(os.path.join(dirpath, fn), encoding="utf-8") as f:
                    used |= set(re.findall(r"R\.(string|array)\.([a-z0-9_]+)", f.read()))
    defined = {("string", k) for k in keys} | {("array", k) for k in ARRAYS}
    missing = sorted(used - defined)
    unused = sorted(defined - used)
    if missing:
        sys.exit(f"missing resources: {missing}")
    print(f"{len(keys)} strings, {len(ARRAYS)} arrays written; unused: {[k for _, k in unused]}")

if __name__ == "__main__":
    main()
